/** 读系统语言：含 TW/HK/MO/Hant → zh-TW；含 zh → zh-CN；否则 en */
function resolveSystemLang() {
  var nav = (typeof navigator !== 'undefined') ? navigator : {};
  var lang = String(nav.language || (nav.languages && nav.languages[0]) || 'en');
  var U = lang.toUpperCase();
  if (/TW|HK|MO|HANT/.test(U)) return 'zh-TW';
  if (U.indexOf('ZH') !== -1) return 'zh-CN';
  return 'en';
}

/** 当前生效语言（system 时解析为具体语言） */
function curLang() {
  var code = 'system';
  try { code = localStorage.getItem(STORE_KEY) || 'system'; } catch (e) {}
  if (!LANG_CODES[code]) code = 'system';
  return code === 'system' ? resolveSystemLang() : code;
}

/** 用户选择的原始 code（含 'system'），用于设置页回显 */
function savedLang() {
  var code = 'system';
  try { code = localStorage.getItem(STORE_KEY) || 'system'; } catch (e) {}
  return LANG_CODES[code] ? code : 'system';
}

var _langListeners = [];
/** 注册语言变更回调（切语言时重渲染 DOM） */
function onLangChange(fn) {
  if (typeof fn === 'function' && _langListeners.indexOf(fn) < 0) _langListeners.push(fn);
}

/** 切换语言：写 localStorage → 触发回调 + DOM 事件 */
function setLang(code) {
  if (!LANG_CODES[code]) code = 'system';
  try { localStorage.setItem(STORE_KEY, code); } catch (e) {}
  var eff = code === 'system' ? resolveSystemLang() : code;
  for (var i = 0; i < _langListeners.length; i++) {
    try { _langListeners[i](code, eff); } catch (e) { if (window.console) console.error(e); }
  }
  try {
    window.dispatchEvent(new CustomEvent('cw:langchange', { detail: { code: code, effective: eff } }));
  } catch (e) {}
}

/**
 * 查当前语言文案，支持 %1$s / %1$d / %1$.2f / %.1f 占位符。
 * 缺 key 或当前语言缺条目 → 回退英文；英文也没有 → 原样返回 key（不抛错、不显示 undefined）。
 */
function t(key) {
  var e = DICT[key];
  var s;
  if (e) {
    s = e[curLang()];
    if (s === undefined || s === null) s = e[FALLBACK];
  }
  if (s === undefined || s === null) return key;
  var args = arguments;
  if (args.length <= 1) return s;
  var pos = 0;
  return String(s).replace(/%(?:(\d+)\$)?(?:\.(\d+))?([sdf])/g, function (all, idx, prec, conv) {
    var v = args[idx ? parseInt(idx, 10) : pos++];
    if (v === undefined) return all;
    if (conv === 'f') return Number(v).toFixed(prec ? parseInt(prec, 10) : 0);
    if (conv === 'd') return String(Math.round(Number(v)));
    return String(v);
  });
}

